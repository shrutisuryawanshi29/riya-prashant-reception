import assert from 'node:assert/strict';
import fs from 'node:fs';
import { stripTypeScriptTypes } from 'node:module';
const compile = source => 'data:text/javascript;base64,' + Buffer.from(stripTypeScriptTypes(source)).toString('base64');
const data = compile(fs.readFileSync('src/receptionData.ts','utf8'));
const calendar = await import(compile(fs.readFileSync('src/utils/calendarUtils.ts','utf8').replace("'../receptionData'", JSON.stringify(data))));
assert.equal(calendar.calendarEvents.length,1);
const event = calendar.calendarEvents[0];
assert.equal(calendar.utcStamp(event.start),'20261206T123000Z');
assert.match(event.location,/Nova Banquet Hall/);
const url = new URL(calendar.googleCalendarUrl(event));
assert.equal(url.searchParams.get('ctz'),'Asia/Kolkata');
assert.equal(url.searchParams.get('dates'),'20261206T123000Z/20261206T123000Z');
const ics = calendar.createICS(event);
assert.ok(ics.includes('DTSTART:20261206T123000Z'));
assert.ok(!ics.includes('DTEND:'));
assert.ok(!/Maharaja|Mehendi|Muhurat/.test(event.description));
const html=fs.readFileSync('dist/index.html','utf8');
assert.ok(html.includes('Our Reception Invitation'));
assert.ok(!/3 December 2026|Nagpur/.test(html));
assert.ok(html.includes('/images/reception-social-preview.jpg'));
const bundle=fs.readdirSync('dist/assets').filter(name=>name.endsWith('.js')).map(name=>fs.readFileSync('dist/assets/'+name,'utf8')).join('');
assert.ok(!/Row House C-06|Maharaja Celebrations|2026-12-03|10:15 AM/.test(bundle));
assert.equal(new Date('2026-12-06T18:00:00+05:30').toISOString(),'2026-12-06T12:30:00.000Z');
console.log('Passed reception calendar, venue, time zone, unknown end and metadata checks.');
